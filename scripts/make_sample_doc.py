"""生成示例文档 —— 让体验者不用自己找 PDF 就能上手.

为什么提供样本
--------------
首次体验路径是"装依赖 → 配 Key → 启动 → 上传 PDF → 提问".
其中**"找一份合适的 PDF"是隐形但真实的阻塞点**: 手边不一定有合适的文档,
随手找一份可能是扫描件(直接失败)或内容太散(看不出检索效果).

这份样本刻意包含四种要素, 覆盖系统的各项能力:

1. **多章节结构** —— 展示标题识别与父子块切分
2. **型号、数字、日期** —— 展示关键词检索那一路的价值(向量对数字不敏感)
3. **跨页重复的页眉页脚** —— 展示跨页重复检测
4. **足够的内容量** —— 能产出几十个分块, 检索差异看得出来

用法::

    python scripts/make_sample_doc.py
    # 输出 samples/NX-3000设备维护手册-示例.pdf
"""

