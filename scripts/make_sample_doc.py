def _wrap(text: str, width: int = 38) -> list[str]:
    return [text[i : i + width] for i in range(0, len(text), width)]


_CN_DIGITS = {
    "一": 1,
    "二": 2,
    "三": 3,
    "四": 4,
    "五": 5,
    "六": 6,
    "七": 7,
    "八": 8,
    "九": 9,
    "十": 10,
}


def _chapter_number(chapter: str) -> str:
    """从"第二章 钢刀维护规范"里取出 2, 用于生成小节号 2.1 / 2.2."""
    for char, value in _CN_DIGITS.items():
        if f"第{char}章" in chapter:
            return str(value)
    return "1"


def build_manual(path: Path) -> tuple[int, int]:
    """生成示例手册, 返回 (页数, 字节数)."""
    import pymupdf as fitz

    doc = fitz.open()

    # ---------------- 封面 ----------------
    # 不做目录页: 目录条目字号偏大, 会被标题识别规则判为标题, 于是一个目录条
    # 就开一个新"章节", 产生一堆只有几个字的父块. 对演示来说这是纯噪声.
    cover = doc.new_page(width=595, height=842)
    cover.insert_text((120, 300), TITLE, fontsize=20, fontname="china-s")
    cover.insert_text((190, 350), "示例文档 · 用于功能演示", fontsize=11, fontname="china-s")
    cover.insert_text(
        (140, 390),
        "本文件为虚构内容，仅用于演示文档解析与检索能力",
        fontsize=9,
        fontname="china-s",
    )

    # ---------------- 正文 ----------------
    # 每章单独起页; 段落按小节分组, 小节标题用章号.节号
    #
    # 注意**不要**给每个段落都加小标题:
    # 第一版这么做了, 结果 2041 字里识别出 38 个标题 → 38 个父块各含 1 个
    # 3~111 字的子块, 完全展示不出父子块的两层结构.
    # 现在的做法是"章节标题 + 若干段落", 让一个父块能容纳多个子块.
    cursor_page = None
    y = 0.0

    def ensure_page(needed: float = 60.0):
        """确保当前页还有空间, 不够就新开一页."""
        nonlocal cursor_page, y
        if cursor_page is None or y + needed > 770:
            cursor_page = _new_page(doc)
            y = 90.0
        return cursor_page

    for chapter, paragraphs in CHAPTERS:
        cursor_page = None  # 每章从新页开始
        ensure_page(120)
        cursor_page.insert_text((56, y), chapter, fontsize=16, fontname="china-s")
        y += 34

        for paragraph in paragraphs:
            ensure_page(70)
            for line in _wrap(paragraph):
                ensure_page(24)
                cursor_page.insert_text((66, y), line, fontsize=10, fontname="china-s")
                y += 18

            y += 14

    doc.save(str(path), deflate=True)
    total = doc.page_count
    doc.close()

    # 页脚的总页数在排版完成后才确定, 所以开新的一份填回去
    _fill_footers(path, total)
    return total, path.stat().st_size


def _new_page(doc):
    """新建一页并加上页眉(页脚留到第二轮统一填)."""
    page = doc.new_page(width=595, height=842)
    page.insert_text((56, 40), HEADER_LEFT, fontsize=8, fontname="china-s")
    page.insert_text((430, 40), HEADER_RIGHT, fontsize=8, fontname="china-s")
    return page


def _fill_footers(path: Path, total: int) -> None:
    """回填页脚.

    页脚刻意写成"页码每页不同、结构完全一致"的形式 ——
    这正是跨页重复检测要处理的典型形态(归一化后 `#` 号相同, 于是被判为页脚).
    用它来演示"自动识别并剔除页眉页脚"是顺手的.
    """
    import pymupdf as fitz

    doc = fitz.open(str(path))
    if doc.page_count != total:
        total = doc.page_count

    for index, page in enumerate(doc):
        if index < 2:  # 封面与目录不加页码
            continue
        page.insert_text(
            (240, 812),
            f"第 {index + 1} 页 / 共 {total} 页 · 文档编号 NX3K-MNT-2026",
            fontsize=8,
            fontname="china-s",
        )

    doc.saveIncr()
    doc.close()


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    target = OUT_DIR / OUT_NAME

    print(f"生成示例文档: {target.name}")
    pages, size = build_manual(target)

    import pymupdf as fitz

    doc = fitz.open(str(target))
    chars = sum(len(p.get_text()) for p in doc)
    doc.close()

    print(f"  完成: {pages} 页, {chars:,} 字符, {size / 1024:.0f} KB")
    print(f"  路径: {target}")
    print()
    print("用它体验: 启动服务后打开 http://127.0.0.1:8000 , 把这个文件拖进上传区。")
    return 0


